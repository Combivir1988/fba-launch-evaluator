// План измерений после запуска (spec 020). Приложение отвечало «заходить или нет» и замолкало;
// гайд требует ДО старта продаж решить, что отслеживать, как часто и ПРИ КАКИХ ЗНАЧЕНИЯХ вмешаться.
//
// Главное: пороги не придумываются и не копируются из статьи, а ВЫЧИСЛЯЮТСЯ из чисел этой ниши.
// План с чужими числами одинаков для ниши с маржой 40 % и для ниши с маржой 12 %, то есть бесполезен.
// Сами показатели после запуска человек смотрит в своём аккаунте продавца — приложение их не собирает.

/** Что смотреть каждый день: это останавливает продажи сразу, а не портит тренд. */
const DAILY = [
  "остаток запаса и дата, когда он кончится",
  "листинг доступен к покупке, не заблокирован",
  "ваше предложение выигрывает Buy Box",
  "цена не слетела после правок или промо",
  "рекламные кампании показываются, бюджет не исчерпан",
  "новые отзывы с жалобой на дефект",
];

/** Что смотреть раз в неделю: здесь важно направление, а не отдельный день. */
const WEEKLY = [
  "трафик: показы и клики по приоритетным запросам",
  "конверсия сессий в заказы",
  "видимость по ключам и доля показов против конкурентов",
  "реклама: расход, доля заказов из рекламы, новые конвертящие запросы",
  "отзывы и рейтинг",
  "возвраты и их причины",
];

/** Сигнал → вероятная причина → что проверить. Расхождение трафика и конверсии почти всегда
 *  указывает на конкретный участок воронки, и лечить надо его, а не всё сразу. */
const DIAGNOSIS = [
  { signal: "Трафика много, конверсия низкая", cause: "Листинг или предложение", check: "цена против конкурентов, отзывы, срок доставки, главное фото, обещания в тексте, понятно ли отличие" },
  { signal: "Трафика мало, конверсия хорошая", cause: "Не хватает видимости", check: "показы и клики по приоритетным ключам, бюджет и ставки рекламы" },
  { signal: "Клики есть, покупок мало", cause: "Трение в середине воронки", check: "добавления в корзину; где проигрываете — цена, доставка, отзывы" },
  { signal: "Отзывы хорошие, продажи слабые", cause: "Товар трудно найти", check: "позиции по ключам и места показа рекламы" },
  { signal: "Продажи растут, доля падает", cause: "Категория растёт быстрее вас", check: "ассортимент, реклама и новый спрос у конкурентов" },
  { signal: "Метрики товара хорошие, экономика слабая", cause: "Перекос расходов", check: "реклама, промо, возвраты, стоимость фулфилмента и доставки" },
];

const num = (v) => (typeof v === "number" && Number.isFinite(v) ? v : null);

/**
 * @param {object} R результаты расчёта
 * @param {object} th пороги
 */
export function launchPlan(R, th) {
  const t = th.launchPlan;
  const eco = R?.economics, cf = R?.cashflow, entry = R?.entry;
  const out = { pending: false, missing: [], thresholds: [], daily: DAILY, weekly: WEEKLY, diagnosis: DIAGNOSIS };

  const add = (key, label, value, unit, from, action) => { if (value !== null) out.thresholds.push({ key, label, value, unit, from, action }); };

  // Не выводится из экономики, и это сказано прямо: вопрос достоверности, а не денег ниши.
  add("sessions", "Сессий, прежде чем судить о конверсии", t.minSessions, "шт",
    "порог из настроек — статистика, а не экономика ниши",
    "до этого числа колебания конверсии считать шумом и ничего не менять");

  const ecoReady = eco && !eco.pending;
  if (!ecoReady) {
    out.pending = true;
    out.missing.push("себестоимость не введена — пороги конверсии и расхода на рекламу посчитать не из чего");
  } else {
    const be = num(eco.breakEvenCvr);
    add("cvr", "Конверсия, ниже которой продажи идут в минус", be, "доля",
      "безубыточный CVR из экономики (уже с учётом возвратов)",
      `проверить цену, фото, отзывы и срок доставки; ниже этого значения каждая продажа убыточна`);

    const net = num(eco.gate1?.net0), price = num(eco.price);
    add("acos", "Расход на рекламу, выше которого прибыль съедена", net !== null && price ? net / price : null, "доля",
      "прибыль на единицу, делённая на цену",
      `пересмотреть ставки и ключи, если держится дольше ${t.acosDaysInRow} дней подряд`);
  }

  const reorder = cf?.reorder;
  if (reorder?.days !== null && reorder?.days !== undefined) {
    add("stock", "Запас, ниже которого пора дозаказывать", reorder.days, "дней",
      `срок всей цепочки поставки ${reorder.leadDays} дн. плюс страховой запас ${reorder.safetyDays} дн.`,
      `разместить заказ; это примерно ${reorder.units} шт остатка`);
  } else if (cf && !cf.pending) {
    out.missing.push("срок поставки не задан — точку дозаказа считать не от чего");
  }

  const rev = entry?.reviews;
  if (rev?.ok && num(rev.threshold) !== null) {
    add("reviews", "Планка отзывов, до которой конверсия ниже", rev.threshold, "шт",
      "планка отзывов из расчёта входа в нишу",
      "до неё держать Vine и купоны; считать конверсию заниженной, а не провальной");
  }

  if (!out.thresholds.some((x) => x.key === "stock")) out.pending = out.pending || out.missing.length > 0;
  return out;
}
